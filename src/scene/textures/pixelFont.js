export const FONT_5x7 = { glyphs: GLYPHS_5x7, width: 5, height: 7, advance: 6, lineHeight: 10 };
export const FONT_3x5 = { glyphs: GLYPHS_3x5, width: 3, height: 5, advance: 4, lineHeight: 7 };

export function measureText(text, font = FONT_5x7) {
    return text.length ? text.length * font.advance - 1 : 0;
}

/**
 * Draws text with its top-left at (x, y). `px(x, y, color)` paints one pixel.
 * vertical: reads bottom-to-top (book spines); (x, y) is then the bottom-left.
 */
export function drawText(px, text, x, y, color, font = FONT_5x7, { vertical = false } = {}) {
    let cursor = 0;
    for (const ch of text) {
        const rows = font.glyphs[ch] ?? font.glyphs[ch.toUpperCase()] ?? font.glyphs[" "];
        rows.forEach((row, ry) => {
            for (let rx = 0; rx < row.length; rx++) {
                if (row[rx] !== "#") continue;
                if (vertical) px(x + ry, y - cursor - rx, color);
                else px(x + cursor + rx, y + ry, color);
            }
        });
        cursor += font.advance;
    }
    return measureText(text, font);
}
